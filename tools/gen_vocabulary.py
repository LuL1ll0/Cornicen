"""Freeze words from public source literals; no runtime source tree is needed."""

import argparse
import ast
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
PUNCTUATION = '.,;:!?()[]{}<>"\''
EXCEPTIONS = (
    'OperationalError', 'IntegrityError', 'DatabaseError', 'JSONDecodeError',
    'HTTPError', 'URLError', 'TOMLDecodeError', 'SSLError', 'TimeoutError',
    'InterfaceError', 'DataError', 'InternalError', 'ProgrammingError',
    'NotSupportedError', 'BadZipFile', 'LargeZipFile', 'IncompleteRead',
    'RemoteDisconnected', 'HTTPException', 'InvalidURL', 'SSLCertVerificationError',
)


def generate(root=ROOT):
    words = {name.casefold() for name in EXCEPTIONS}
    for path in sorted((root / 'src/cornicen').rglob('*.py')):
        if path.name == 'vocabulary.py':
            continue
        tree = ast.parse(path.read_text(encoding='utf-8'))
        docstrings = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                if (node.body and isinstance(node.body[0], ast.Expr)
                        and isinstance(node.body[0].value, ast.Constant)
                        and isinstance(node.body[0].value.value, str)):
                    docstrings.add(id(node.body[0].value))
            if isinstance(node, ast.ClassDef):
                words.add(node.name.casefold())
        for node in ast.walk(tree):
            if not isinstance(node, ast.Constant) or not isinstance(node.value, str) or id(node) in docstrings:
                continue
            for token in node.value.split():
                core = token.strip(PUNCTUATION)
                if (core.isascii() and re.search('[A-Za-z]', core)
                        and not re.search(r'CVE-\d|GHSA-', core, re.IGNORECASE)):
                    words.add(core.casefold())
    return ('# Generated by tools/gen_vocabulary.py; do not edit.\n\nWORDS = frozenset({\n'
            + ''.join(f'    {word!r},\n' for word in sorted(words)) + '})\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/cornicen/vocabulary.py'
    generated = generate()
    if args.check:
        return 0 if target.exists() and target.read_text(encoding='utf-8') == generated else 1
    target.write_text(generated, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
